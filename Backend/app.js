import express from 'express';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import authRoutes from './routes/auth.js';
import universityRoutes from './routes/universities.js';
import shortlistRoutes from './routes/shortlist.js';
import preferenceRoutes from './routes/preferences.js';
import recommendationRoutes from './routes/recommendations.js';
import { notFound, errorHandler } from './middleware/errors.js';
const app=express();
const __dirname=path.dirname(fileURLToPath(import.meta.url));
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:false}));
app.use(express.json({limit:'100kb'}));
app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({ok:true,service:'AbroadMate API'}));
const authLimiter=rateLimit({windowMs:15*60*1000,limit:100,standardHeaders:true,legacyHeaders:false,message:{message:'Too many requests. Please try again later.'}});
app.use('/api/auth',authLimiter,authRoutes);
app.use('/api/universities',universityRoutes);
app.use('/api/shortlist',shortlistRoutes);
app.use('/api/preferences',preferenceRoutes);
app.use('/api/recommendations',recommendationRoutes);
const clientDist=path.resolve(__dirname,'../Frontend/dist');
app.use(express.static(clientDist));
app.get('*',(req,res,next)=>{if(req.path.startsWith('/api/'))return next();res.sendFile(path.join(clientDist,'index.html'),err=>{if(err)next(err);});});
app.use(notFound);
app.use(errorHandler);
export default app;
